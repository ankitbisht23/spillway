// Writes src/api/roles.gen.ts, each operation's roles from its
// x-spillway-roles in api/openapi.yaml (UI-04, ADR-0058): the source the
// server's guard reads (ADR-0040), so the UI's table cannot differ from it.
// Role names are the Me schema's; others are dropped, as the server drops
// them. Usage: node scripts/gen-roles.mjs [output file].
import { readFileSync, writeFileSync } from "node:fs";

import { parse } from "yaml";

const out = process.argv[2] ?? "src/api/roles.gen.ts";
const spec = parse(readFileSync("../api/openapi.yaml", "utf8"));
/** @type {string[]} */
const known = spec.components.schemas.Me.properties.roles.items.enum;
const methods = ["get", "put", "post", "delete", "options", "head", "patch", "trace"];

/** @type {[string, string[]][]} */
const ops = [];
for (const item of Object.values(spec.paths)) {
  for (const method of methods) {
    const op = item[method];
    if (!op) continue;
    const roles = Array.isArray(op["x-spillway-roles"]) ? op["x-spillway-roles"].filter((/** @type {unknown} */ r) => typeof r === "string" && known.includes(r)) : [];
    ops.push([op.operationId, roles]);
  }
}
ops.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const lines = [
  "// Generated by web/scripts/gen-roles.mjs from api/openapi.yaml's",
  "// x-spillway-roles (ADR-0058). Do not edit: run make web-gen.",
  "",
  "/** The roles allowed to call each operation of the admin API. */",
  "export const operationRoles = {",
  ...ops.map(([id, roles]) => `  ${id}: [${roles.map((r) => JSON.stringify(r)).join(", ")}],`),
  "} as const;",
  "",
  "export type OperationId = keyof typeof operationRoles;",
  "",
];
writeFileSync(out, lines.join("\n"));
