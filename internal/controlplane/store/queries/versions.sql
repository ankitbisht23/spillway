-- Validate, publish, published versions and rollback (CP-02 - CP-04,
-- ADR-0037). Each query names the index it relies on; the EXPLAIN test in
-- test/integration checks that none scans a whole table, except the
-- whole-working-set reads and the rollback's replacement of the working
-- tables, which it lists.

-- name: LockWorkingSet :one
-- config_working_set_pkey. Takes the row lock every config writer takes,
-- without bumping the revision: from here every edit, import, publish and
-- rollback waits.
SELECT revision FROM config_working_set WHERE id = 1 FOR UPDATE;

-- name: WorkingSetRevision :one
-- config_working_set_pkey.
SELECT revision FROM config_working_set WHERE id = 1;

-- name: AllUpstreams :many
-- The whole working set.
SELECT * FROM upstreams ORDER BY id;

-- name: AllEndpoints :many
-- The whole working set.
SELECT * FROM endpoints ORDER BY upstream_id, id;

-- name: AllRoutes :many
-- The whole working set.
SELECT * FROM routes ORDER BY id;

-- name: AllPolicies :many
-- The whole working set.
SELECT * FROM policies ORDER BY id;

-- name: AllPlans :many
-- The whole working set.
SELECT * FROM plans ORDER BY id;

-- name: TenantsOnPlans :many
-- tenants_plan_id.
SELECT id, name, plan_id FROM tenants WHERE plan_id = ANY(@plan_ids::bigint[]) ORDER BY id;

-- name: ConsumersOnPlans :many
-- consumers_plan_id (partial: plan_id = ANY implies plan_id IS NOT NULL).
SELECT id, name, plan_id FROM consumers WHERE plan_id = ANY(@plan_ids::bigint[]) ORDER BY id;

-- name: OverridesOnPolicies :many
-- overrides_policy_id.
SELECT id, consumer_id, policy_id FROM overrides WHERE policy_id = ANY(@policy_ids::bigint[]) ORDER BY id;

-- name: InsertConfigVersion :one
-- published_at is taken here, after validation and before the audit
-- record, the NOTIFY and the commit (NFR-08's "publish committed",
-- ADR-0037).
INSERT INTO config_versions (version, published_at, published_by, note, kind, rollback_of, working_set_revision, schema_major, schema_minor, snapshot)
VALUES (@version, clock_timestamp(), @published_by, @note, @kind, sqlc.narg(rollback_of), @working_set_revision, @schema_major, @schema_minor, @snapshot)
RETURNING *;

-- name: NotifyConfig :exec
-- Delivered at commit to the Watch streams' LISTEN (CP-22, ADR-0038).
SELECT pg_notify('spillway_config', @version::text);

-- name: ListConfigVersions :many
-- config_versions_pkey backward keyset scan; without the snapshots.
SELECT version, published_at, published_by, note, kind, rollback_of, working_set_revision, schema_major, schema_minor
FROM config_versions WHERE version < @before::bigint ORDER BY version DESC LIMIT @lim;

-- name: GetConfigVersion :one
-- config_versions_pkey.
SELECT * FROM config_versions WHERE version = @version;

-- name: DeleteAllUpstreams :exec
-- A rollback replaces the working tables; endpoints go by the cascade.
DELETE FROM upstreams;

-- name: DeleteAllRoutes :exec
-- A rollback replaces the working tables.
DELETE FROM routes;

-- name: DeleteAllPolicies :exec
-- A rollback replaces the working tables.
DELETE FROM policies;

-- name: DeleteAllPlans :exec
-- A rollback replaces the working tables.
DELETE FROM plans;

-- name: RestoreUpstream :exec
-- Under its original ID (ADR-0036's GENERATED BY DEFAULT); created_at kept
-- when the row was in the working set.
INSERT INTO upstreams (id, name, spec, version, created_at)
VALUES (@id, @name, @spec, @version, coalesce(sqlc.narg(created_at)::timestamptz, clock_timestamp()));

-- name: RestoreEndpoint :exec
INSERT INTO endpoints (id, upstream_id, address, draining, created_at)
VALUES (@id, @upstream_id, @address, @draining, coalesce(sqlc.narg(created_at)::timestamptz, clock_timestamp()));

-- name: RestoreRoute :exec
INSERT INTO routes (id, name, spec, version, created_at)
VALUES (@id, @name, @spec, @version, coalesce(sqlc.narg(created_at)::timestamptz, clock_timestamp()));

-- name: RestorePolicy :exec
INSERT INTO policies (id, name, spec, version, created_at)
VALUES (@id, @name, @spec, @version, coalesce(sqlc.narg(created_at)::timestamptz, clock_timestamp()));

-- name: RestorePlan :exec
INSERT INTO plans (id, name, spec, version, created_at)
VALUES (@id, @name, @spec, @version, coalesce(sqlc.narg(created_at)::timestamptz, clock_timestamp()));

-- name: LatestVersions :one
-- config_versions_pkey backward scan and identity_state_pkey: the newest
-- config and identity versions, which the broadcaster compares with what it
-- holds every 10 s (ADR-0038).
SELECT (SELECT coalesce(max(version), 0) FROM config_versions)::bigint AS config_version,
       (SELECT version FROM identity_state WHERE id = 1)::bigint AS identity_version;
