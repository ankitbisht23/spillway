-- The control plane's first schema (CP-01, CP-19, ADR-0036): the config
-- working set and its published versions, the identity tables, and the app
-- role. Forward-only: there is no Down section; a bad migration is fixed by
-- the next one. Release that may contract anything added here: none needed,
-- this release only adds.

-- +goose Up

-- The app role (ADR-0040). `controlplane serve` connects as it; `controlplane
-- migrate` gives it a login and password after the migrations. Roles are
-- cluster-wide, so it may already exist (another database on the server).
-- +goose StatementBegin
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'spillway_app') THEN
        CREATE ROLE spillway_app NOLOGIN;
    END IF;
END
$$;
-- +goose StatementEnd

-- Tables created from here on by the migrating owner get the app's grants.
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO spillway_app;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT USAGE ON SEQUENCES TO spillway_app;
GRANT SELECT ON goose_db_version TO spillway_app;

-- Config working set (CP-01, CP-02, ADR-0037). Every config edit bumps
-- revision first; its row lock serializes config writers.
CREATE TABLE config_working_set (
    id         smallint PRIMARY KEY CHECK (id = 1),
    revision   bigint NOT NULL,
    updated_by text,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
INSERT INTO config_working_set (id, revision) VALUES (1, 1);

-- Config entities keep their proto message in spec (protojson, proto field
-- names), without the fields that have columns (CP-21, ADR-0036).
CREATE TABLE upstreams (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL UNIQUE CHECK (name ~ '^[A-Za-z0-9._-]{1,64}$'),
    spec       jsonb NOT NULL,
    version    bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE endpoints (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    upstream_id bigint NOT NULL REFERENCES upstreams ON DELETE CASCADE,
    address     text NOT NULL,
    draining    boolean NOT NULL DEFAULT false,
    created_at  timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at  timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (upstream_id, address)
);

CREATE TABLE routes (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL UNIQUE CHECK (name ~ '^[A-Za-z0-9._-]{1,64}$'),
    spec       jsonb NOT NULL,
    version    bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE policies (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL UNIQUE CHECK (name ~ '^[A-Za-z0-9._-]{1,64}$'),
    spec       jsonb NOT NULL,
    version    bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE plans (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL UNIQUE CHECK (name ~ '^[A-Za-z0-9._-]{1,64}$'),
    spec       jsonb NOT NULL,
    version    bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

-- Published config versions (CP-02, CP-04, ADR-0037); written by the publish
-- task. The latest is a backward scan of the primary key.
CREATE TABLE config_versions (
    version              bigint PRIMARY KEY,
    published_at         timestamptz NOT NULL,
    published_by         text NOT NULL,
    note                 text NOT NULL CHECK (length(note) BETWEEN 1 AND 2000),
    kind                 text NOT NULL CHECK (kind IN ('publish', 'rollback')),
    rollback_of          bigint REFERENCES config_versions,
    working_set_revision bigint NOT NULL,
    schema_major         int NOT NULL,
    schema_minor         int NOT NULL,
    snapshot             jsonb NOT NULL,
    created_at           timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at           timestamptz NOT NULL DEFAULT clock_timestamp()
);

-- Identity (CP-01, CP-20, ADR-0037). Every identity change bumps version
-- first; its row lock orders identity changes, so versions follow commit
-- order. Version 1 is the empty identity.
CREATE TABLE identity_state (
    id         smallint PRIMARY KEY CHECK (id = 1),
    version    bigint NOT NULL,
    changed_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
INSERT INTO identity_state (id, version, changed_at) VALUES (1, 1, clock_timestamp());

-- Identity rows refer to config (plan_id, policy_id) by ID without foreign
-- keys: the reference is checked against the latest published config
-- (ADR-0037).
CREATE TABLE tenants (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text NOT NULL UNIQUE CHECK (name ~ '^[A-Za-z0-9._-]{1,64}$'),
    plan_id    bigint NOT NULL,
    status     text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended')),
    version    bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX tenants_plan_id ON tenants (plan_id);

CREATE TABLE consumers (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   bigint NOT NULL REFERENCES tenants ON DELETE RESTRICT,
    name        text NOT NULL CHECK (name ~ '^[A-Za-z0-9._-]{1,64}$'),
    plan_id     bigint, -- NULL: the tenant's plan
    status      text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended')),
    jwt_subject text UNIQUE,
    version     bigint NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at  timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (tenant_id, name)
);
CREATE INDEX consumers_plan_id ON consumers (plan_id) WHERE plan_id IS NOT NULL;

CREATE TABLE api_keys (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer_id  bigint NOT NULL REFERENCES consumers ON DELETE CASCADE,
    prefix       text NOT NULL UNIQUE CHECK (prefix ~ '^[0-9A-Za-z]{8}$'),
    hash         bytea NOT NULL CHECK (length(hash) = 32),
    expires_at   timestamptz,
    revoked_at   timestamptz,
    rotated_from bigint REFERENCES api_keys,
    version      bigint NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at   timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX api_keys_consumer_id ON api_keys (consumer_id, id);
CREATE INDEX api_keys_rotated_from ON api_keys (rotated_from) WHERE rotated_from IS NOT NULL;

CREATE TABLE access_lists (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action       text NOT NULL CHECK (action IN ('allow', 'deny')),
    subject_type text NOT NULL CHECK (subject_type IN ('key', 'consumer', 'cidr')),
    api_key_id   bigint REFERENCES api_keys ON DELETE CASCADE,
    consumer_id  bigint REFERENCES consumers ON DELETE CASCADE,
    cidr         cidr,
    note         text,
    version      bigint NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at   timestamptz NOT NULL DEFAULT clock_timestamp(),
    -- Exactly the subject_type's column is set.
    CHECK ((api_key_id IS NOT NULL) = (subject_type = 'key')
       AND (consumer_id IS NOT NULL) = (subject_type = 'consumer')
       AND (cidr IS NOT NULL) = (subject_type = 'cidr'))
);
CREATE UNIQUE INDEX access_lists_key ON access_lists (action, api_key_id) WHERE api_key_id IS NOT NULL;
CREATE UNIQUE INDEX access_lists_consumer ON access_lists (action, consumer_id) WHERE consumer_id IS NOT NULL;
CREATE UNIQUE INDEX access_lists_cidr ON access_lists (action, cidr) WHERE cidr IS NOT NULL;

-- policy_id's CHECK goes in M7 for quota overrides (RL-10).
CREATE TABLE overrides (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consumer_id bigint NOT NULL REFERENCES consumers ON DELETE CASCADE,
    policy_id   bigint CHECK (policy_id IS NOT NULL),
    limits      jsonb NOT NULL,
    quotas      jsonb,
    starts_at   timestamptz,
    ends_at     timestamptz,
    note        text,
    version     bigint NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at  timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (starts_at IS NULL OR ends_at IS NULL OR ends_at > starts_at)
);
CREATE INDEX overrides_consumer_policy ON overrides (consumer_id, policy_id);
-- At most one standing override per (consumer, policy) (ADR-0041).
CREATE UNIQUE INDEX overrides_standing ON overrides (consumer_id, policy_id) WHERE ends_at IS NULL;
CREATE INDEX overrides_policy_id ON overrides (policy_id);
